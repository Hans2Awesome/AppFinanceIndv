"""Transaction repository shared by the API and the Telegram bot."""

from __future__ import annotations

import json
import sqlite3
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timezone

from .connection import is_postgres

_UNSET = object()

_SELECT = """
    SELECT t.id, t.user_id, t.type, t.category_id, c.name AS category_name,
           t.amount, t.note, t.asset_name, t.transaction_date, t.source_key
    FROM transactions t
    LEFT JOIN categories c ON t.category_id = c.id
"""

# Cash rows generated from a debt or an installment belong to that record. They
# stay read-only here so the debt balance and the cash ledger cannot drift.
DERIVED_SOURCE_PREFIXES = ("debt:", "debt_payment:")


class DerivedTransactionError(ValueError):
    """Raised when a transaction generated by another record is edited directly."""


@dataclass(frozen=True)
class Transaction:
    """A financial transaction persisted in SQLite."""

    id: int
    user_id: int
    type: str
    category_id: int | None
    amount: int
    note: str | None
    asset_name: str | None
    transaction_date: str
    category_name: str | None = None
    source_key: str | None = None

    @property
    def can_edit(self) -> bool:
        return not is_derived_transaction(self)

    @property
    def can_delete(self) -> bool:
        return not is_derived_transaction(self)


def is_derived_transaction(transaction: Transaction | None) -> bool:
    """Return True when the row was generated from a debt or installment."""

    if transaction is None or not transaction.source_key:
        return False
    return transaction.source_key.startswith(DERIVED_SOURCE_PREFIXES)


def _row_to_transaction(row: sqlite3.Row) -> Transaction:
    keys = row.keys()
    return Transaction(
        id=row["id"],
        user_id=row["user_id"],
        type=row["type"],
        category_id=row["category_id"],
        amount=row["amount"],
        note=row["note"],
        asset_name=row["asset_name"],
        transaction_date=row["transaction_date"],
        category_name=row["category_name"] if "category_name" in keys else None,
        source_key=row["source_key"] if "source_key" in keys else None,
    )


def create_transaction(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    type: str,
    category_id: int | None,
    amount: int,
    note: str | None,
    asset_name: str | None,
    transaction_date: str,
    source_key: str | None = None,
) -> Transaction:
    """Create and return a transaction for one user.

    ``source_key`` marks a transaction generated by another record, such as a
    recurring schedule or a debt. A unique index on that column keeps the same
    source from being posted twice.
    """

    cursor = connection.execute(
        """
        INSERT INTO transactions (
            user_id, type, category_id, amount, note, asset_name,
            transaction_date, source_key
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            user_id,
            type,
            category_id,
            amount,
            note,
            asset_name,
            transaction_date,
            source_key,
        ),
    )

    transaction = get_transaction_by_id(
        connection,
        user_id=user_id,
        transaction_id=cursor.lastrowid,
    )
    if transaction is None:
        raise RuntimeError("Failed to create transaction")
    return transaction


def get_transaction_by_id(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    transaction_id: int,
) -> Transaction | None:
    """Fetch one owned transaction with its category name."""

    row = connection.execute(
        _SELECT + " WHERE t.id = ? AND t.user_id = ?",
        (transaction_id, user_id),
    ).fetchone()
    return None if row is None else _row_to_transaction(row)


def list_transactions(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    start_date: str | None = None,
    end_date: str | None = None,
    transaction_type: str | None = None,
    limit: int | None = None,
    offset: int = 0,
) -> list[Transaction]:
    """List owned transactions, newest first, with optional filters."""

    query = _SELECT + " WHERE t.user_id = ?"
    params: list = [user_id]

    if start_date:
        query += " AND t.transaction_date >= ?"
        params.append(start_date)
    if end_date:
        query += " AND t.transaction_date <= ?"
        params.append(end_date)
    if transaction_type:
        query += " AND t.type = ?"
        params.append(transaction_type)

    query += " ORDER BY t.transaction_date DESC, t.id DESC"
    if limit is not None:
        query += " LIMIT ? OFFSET ?"
        params.extend([limit, offset])

    rows = connection.execute(query, tuple(params)).fetchall()
    return [_row_to_transaction(row) for row in rows]


def list_transactions_by_type(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    transaction_type: str,
    limit: int,
    offset: int = 0,
) -> list[Transaction]:
    """List owned transactions of one type, newest first, paginated."""

    return list_transactions(
        connection,
        user_id=user_id,
        transaction_type=transaction_type,
        limit=limit,
        offset=offset,
    )


def count_transactions_by_type(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    transaction_type: str,
) -> int:
    """Count owned transactions of one type."""

    row = connection.execute(
        "SELECT COUNT(*) FROM transactions WHERE user_id = ? AND type = ?",
        (user_id, transaction_type),
    ).fetchone()
    return int(row[0])


def list_transactions_in_range(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    start_date: str,
    end_date: str,
) -> list[Transaction]:
    """List owned transactions in an inclusive range, oldest first."""

    rows = connection.execute(
        _SELECT
        + """
        WHERE t.user_id = ? AND t.transaction_date BETWEEN ? AND ?
        ORDER BY t.transaction_date ASC, t.id ASC
        """,
        (user_id, start_date, end_date),
    ).fetchall()
    return [_row_to_transaction(row) for row in rows]


def update_transaction(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    transaction_id: int,
    amount: int | None = None,
    category_id: int | None | object = _UNSET,
    transaction_date: str | None = None,
    note: str | None | object = _UNSET,
    asset_name: str | None | object = _UNSET,
    source: str = "system",
    reason: str = "direct",
) -> Transaction | None:
    """Update editable fields for an owned transaction."""

    with _locked_mutation(connection, user_id, transaction_id):
        return _update_locked(
            connection,
            user_id=user_id,
            transaction_id=transaction_id,
            amount=amount,
            category_id=category_id,
            transaction_date=transaction_date,
            note=note,
            asset_name=asset_name,
            source=source,
            reason=reason,
        )


def _update_locked(
    connection,
    *,
    user_id,
    transaction_id,
    amount,
    category_id,
    transaction_date,
    note,
    asset_name,
    source,
    reason,
):
    current = get_transaction_by_id(connection, user_id=user_id, transaction_id=transaction_id)
    if current is None:
        return None
    if is_derived_transaction(current) and reason != "debt_sync":
        raise DerivedTransactionError(
            "Transaksi ini berasal dari utang/piutang. Ubah lewat menu Utang."
        )

    values = (
        amount if amount is not None else current.amount,
        current.category_id if category_id is _UNSET else category_id,
        transaction_date if transaction_date is not None else current.transaction_date,
        current.note if note is _UNSET else note,
        current.asset_name if asset_name is _UNSET else asset_name,
    )
    if values == (
        current.amount,
        current.category_id,
        current.transaction_date,
        current.note,
        current.asset_name,
    ):
        return current
    connection.execute(
        """
        UPDATE transactions
        SET amount = ?, category_id = ?, transaction_date = ?, note = ?, asset_name = ?,
            updated_at = CURRENT_TIMESTAMP
        WHERE id = ? AND user_id = ?
        """,
        (*values, transaction_id, user_id),
    )
    updated = get_transaction_by_id(connection, user_id=user_id, transaction_id=transaction_id)
    _append_history(connection, current, updated, source, reason)
    return updated


def delete_transaction(
    connection: sqlite3.Connection,
    *,
    user_id: int,
    transaction_id: int,
    source: str = "system",
    reason: str = "direct",
) -> bool:
    """Delete one owned transaction.

    Rows generated from a debt or installment are rejected: deleting them would
    leave the debt record claiming a payment that no longer exists in the cash
    ledger. Delete the debt instead, which removes both sides.
    """

    with _locked_mutation(connection, user_id, transaction_id):
        return _delete_locked(connection, user_id, transaction_id, source, reason)


def _delete_locked(connection, user_id, transaction_id, source, reason):
    current = get_transaction_by_id(connection, user_id=user_id, transaction_id=transaction_id)
    if current is None:
        return False
    if is_derived_transaction(current) and reason not in ("debt_delete", "payment_delete"):
        raise DerivedTransactionError(
            "Transaksi ini berasal dari utang/piutang. Hapus lewat menu Utang."
        )

    cursor = connection.execute(
        "DELETE FROM transactions WHERE id = ? AND user_id = ?",
        (transaction_id, user_id),
    )
    if cursor.rowcount != 1:
        return False
    _append_history(connection, current, None, source, reason)
    return True


@contextmanager
def _locked_mutation(connection, user_id, transaction_id):
    """Lock before reading and roll back failed audit writes without committing."""

    if is_postgres(connection):
        connection.execute(
            "SELECT id FROM transactions WHERE id = ? AND user_id = ? FOR UPDATE",
            (transaction_id, user_id),
        ).fetchone()
    else:
        # A SELECT alone does not start a transaction in sqlite3 legacy mode.
        connection.execute(
            "UPDATE transactions SET updated_at = updated_at WHERE id = ? AND user_id = ?",
            (transaction_id, user_id),
        )
    connection.execute("SAVEPOINT transaction_audit_write")
    try:
        yield
    except BaseException:
        connection.execute("ROLLBACK TO SAVEPOINT transaction_audit_write")
        connection.execute("RELEASE SAVEPOINT transaction_audit_write")
        raise
    else:
        connection.execute("RELEASE SAVEPOINT transaction_audit_write")


def _snapshot(item: Transaction) -> dict:
    return {
        field: getattr(item, field)
        for field in (
            "id",
            "type",
            "category_id",
            "category_name",
            "amount",
            "note",
            "asset_name",
            "transaction_date",
            "source_key",
        )
    }


def _append_history(connection, before, after, source, reason):
    connection.execute(
        """INSERT INTO transaction_audit
           (user_id, transaction_id, action, source, reason,
            before_snapshot, after_snapshot, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
        (
            before.user_id,
            before.id,
            "delete" if after is None else "update",
            source,
            reason,
            json.dumps(_snapshot(before), ensure_ascii=False),
            json.dumps(_snapshot(after), ensure_ascii=False) if after is not None else None,
            datetime.now(timezone.utc).isoformat(),
        ),
    )


def list_transaction_history(
    connection,
    *,
    user_id: int,
    transaction_id: int | None = None,
    limit: int = 50,
    offset: int = 0,
) -> list[dict]:
    """Read immutable snapshots even after the live transaction is gone."""

    query = "SELECT * FROM transaction_audit WHERE user_id = ?"
    params = [user_id]
    if transaction_id is not None:
        query += " AND transaction_id = ?"
        params.append(transaction_id)
    query += " ORDER BY id DESC LIMIT ? OFFSET ?"
    params.extend([limit, offset])
    result = []
    for row in connection.execute(query, tuple(params)).fetchall():
        item = dict(row)
        item["before"] = json.loads(item.pop("before_snapshot"))
        after = item.pop("after_snapshot")
        item["after"] = json.loads(after) if after else None
        item.pop("user_id")
        result.append(item)
    return result
