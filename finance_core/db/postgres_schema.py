def run_postgres_migrations(connection: Any) -> int:
    """Apply every pending PostgreSQL migration and return the schema version."""

    from .connection import transaction
    from .migrations import SCHEMA_VERSION, current_version

    with transaction(connection):
        connection.execute(
            f"""
            CREATE TABLE IF NOT EXISTS schema_migrations (
                version INTEGER PRIMARY KEY,
                applied_at TEXT NOT NULL DEFAULT {_TIMESTAMP}
            )
            """
        )
        applied = {
            int(row["version"])
            for row in connection.execute("SELECT version FROM schema_migrations").fetchall()
        }

        for version in sorted(_POSTGRES_MIGRATIONS):
            if version in applied:
                continue
            statements = _POSTGRES_MIGRATIONS[version]
            with transaction(connection):
                _apply(statements, connection)
                connection.execute(
                    "INSERT INTO schema_migrations (version) VALUES (?)",
                    (version,),
                )

        version = current_version(connection)

    if version != SCHEMA_VERSION:
        raise RuntimeError(
            f"PostgreSQL schema is at version {version}, expected {SCHEMA_VERSION}."
        )
    return version


